def engine_state(board, cells, next_input=2):
    state = game.new_game(123,7)
    state.update(towerLimit=cells,nextId=len(board),gameOver=False,queue=[next_input,4,None,None])
    state['tower'] = [{'id':f't{i+1}','value':b.value,'kind':'group' if b.group else 'tile',
                       'physicalCount':b.span} for i,b in enumerate(board)]
    return state


def exhaustive_actions(planner, target, maximum):
    # Independent BFS with transitions generated by the fixed game engine.
    start = (planner.initial,None,0)
    queue,visited = deque([(start,0)]),{start}
    while queue:
        (board,last,repeats),depth = queue.popleft()
        if any(b.value==target and not b.group for b in board):
            return depth
        if sum(b.span for b in board)>=planner.cells:
            continue
        actions = []
        for kind in ('drop','up','down'):
            for value in planner.inputs:
                if value!=last or repeats<4:
                    actions.append(({'kind':kind},value,value,repeats+1 if value==last else 1))
        actions.append(({'kind':'edge'},2,last,repeats))
        for first in range(len(board)):
            for end in range(first+2,min(first+5,len(board))+1):
                actions.append(({'kind':'group','indices':list(range(first,end))},2,last,repeats))
        for action,value,next_last,next_repeats in actions:
            try:after = game.apply(engine_state(board,planner.cells,value),action,sample=False)
            except ValueError:continue
            blocks = tuple(Block(t['value'],t['physicalCount'],t['kind']=='group') for t in after['tower'])
            if any(b.value>maximum for b in blocks):
                continue
            state = (blocks,next_last,next_repeats)
            if state not in visited:
                visited.add(state); queue.append((state,depth+1))


class NonstandardBaseTests(unittest.TestCase):
    def test_successors_match_engine_including_rotation_drop_and_group_span(self):
        boards = [(),(Block(2),Block(4)),(Block(15),Block(6),Block(10)),
                  (Block(96),Block(30),Block(60)),(Block(72),Block(78,2,True))]
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=5,max_value=200)
            for board in boards:
                for action,after,_,_,drops in planner.successors(board,None,0,200):
                    actual = game.apply(engine_state(board,5,action.get('input',2)),
                                        {k:v for k,v in action.items() if k!='input'},sample=False)
                    expected = tuple(Block(t['value'],t['physicalCount'],t['kind']=='group') for t in actual['tower'])
                    self.assertEqual(after,expected)
                    self.assertEqual(drops,actual['drops'])

    def test_shortest_nonstandard_edge_constructs_its_group_predecessor(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=5,initial=[96,30,60],max_value=100)
            result = planner.search_base(9,exponent=1,node_limit=0)
            self.assertEqual(result['status'],'found')
            self.assertEqual(result['actions'],2)
            self.assertEqual([s['action']['kind'] for s in result['path']],['group','edge'])
            self.assertEqual(result['path'][-1]['after'],[[18,1,False]])
            self.assertTrue(result['shortestInScopeProven'])
            self.assertFalse(result['stochasticReachabilityProven'])
            self.assertIsNone(result['successProbability'])

    def test_minimal_actions_match_independent_engine_bfs(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=3,inputs=[2,4,6],max_value=16)
            for target in (6,8,12,16):
                expected = exhaustive_actions(planner,target,16)
                result = planner.search(target,node_limit=0)
                self.assertEqual(result['actions'],expected)

    def test_drops_objective_charges_no_drop_for_group_or_edge(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=5,initial=[96,30,60],max_value=100,objective='drops')
            result = planner.search(18,node_limit=0)
            self.assertEqual((result['cost'],result['drops'],result['actions']),(0,0,2))

    def test_pause_and_resume_and_completed_query_uses_cache(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=3,inputs=[2,4,6],max_value=16)
            partial = planner.search(16,node_limit=1)
            self.assertEqual(partial['status'],'paused')
            self.assertFalse(partial['shortestInScopeProven'])
            complete = planner.search(16,node_limit=0)
            repeated = planner.search(16,node_limit=0)
            self.assertEqual(complete['path'],repeated['path'])
            self.assertEqual(repeated['search']['nodesThisRun'],0)

    def test_group_target_is_not_an_ordinary_tile_and_full_board_cannot_act(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=3,initial=[Block(6,2,True)],inputs=[2,4],max_value=8)
            result = planner.search(6,node_limit=0)
            self.assertEqual(result['status'],'no-path-in-scope')
            self.assertFalse(result['shortestInScopeProven'])
            full = NonstandardSynthesizer(tmp,cells=2,initial=[2,4],max_value=16)
            self.assertEqual(list(full.successors(full.initial,None,0,16)),[])

    def test_repeat_guard_is_cached_with_the_board(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=5)
            actions = list(planner.successors((Block(2),),2,4,48))
            self.assertFalse(any(a.get('input')==2 for a,*_ in actions))
            self.assertNotEqual(planner._key((),2,3),planner._key((),2,4))

    def test_interrupt_retries_current_expansion_and_scope_changes_do_not_share_proof(self):
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp,cells=5,inputs=[2,4],max_value=20)
            def interrupt(update):
                raise KeyboardInterrupt
            paused = planner.search(14,node_limit=200,progress=interrupt)
            self.assertEqual(paused['status'],'paused')
            self.assertEqual(paused['search']['nodesThisRun'],100)
            self.assertEqual(paused['search']['statesSettled'],99)
            resumed = planner.search(14,node_limit=1)
            self.assertEqual(resumed['search']['statesSettled'],100)
            changed = NonstandardSynthesizer(tmp,cells=5,inputs=[2,4,6],max_value=20).search(14,node_limit=1)
            self.assertNotEqual(changed['search']['cacheId'],paused['search']['cacheId'])
            self.assertEqual(changed['search']['statesSettled'],1)

    def test_odd_base_and_default_edge_ceiling_and_invalid_arguments(self):
        self.assertEqual(odd_base(108),27)
        with tempfile.TemporaryDirectory() as tmp:
            planner = NonstandardSynthesizer(tmp)
            self.assertEqual(planner._config(14)['maxValue'],79)
            bare = planner.search_base(7,exponent=0)
            self.assertEqual(bare['status'],'excluded-by-rules')
            self.assertFalse((Path(tmp)/'synthesis.sqlite3').exists())
            for base in (0,2,True):
                with self.assertRaises(ValueError):planner.search_base(base)
            with self.assertRaises(ValueError):planner.search_base(65535,exponent=1)
            with self.assertRaises(ValueError):NonstandardSynthesizer(tmp,cells=10)

    def test_cli_is_reusable_and_requires_an_explicit_goal(self):
        with tempfile.TemporaryDirectory() as tmp:
            process = subprocess.run(['python','-m','automation.nonstandard_base','--target','6',
                                      '--cells','3','--directory',tmp,'--node-limit','100'],
                                     cwd=Path(__file__).resolve().parents[2],capture_output=True,text=True)
            self.assertEqual(process.returncode,0,process.stderr)
            result = json.loads(process.stdout)
            self.assertEqual(result['target'],6)
            self.assertTrue(result['shortestInScopeProven'])


if __name__=='__main__':
    unittest.main()
